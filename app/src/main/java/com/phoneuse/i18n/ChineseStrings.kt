/** Common navigation, settings, and task text. Unknown provider/card text keeps its English fallback. */
internal object ChineseStrings {
    fun translate(english: String): String = strings[english] ?: when {
        english.matches(Regex("\\d+ needed")) -> "还需 ${english.substringBefore(' ')} 项"
        english.matches(Regex("\\d+ things remembered")) -> "已记住 ${english.substringBefore(' ')} 项"
        english.matches(Regex("\\d+ min")) -> english.substringBefore(' ') + " 分钟"
        english.matches(Regex("\\d+ hours?")) -> english.substringBefore(' ') + " 小时"
        english.matches(Regex("\\d+ h \\d+ min")) -> english.replace(" h ", " 小时 ").replace(" min", " 分钟")
        english.matches(Regex("Wait [0-9]+(?:\\.[0-9]+)? s, then open")) -> "等待 " + english.removePrefix("Wait ").removeSuffix(" s, then open") + " 秒后打开"
        english.startsWith("Once every ") -> "每 " + translate(english.removePrefix("Once every ")) + " 一次"
        english.startsWith("Auto · ") -> "自动 · " + english.removePrefix("Auto · ")
        english.startsWith("Today ") -> "今天 " + english.removePrefix("Today ")
        english.startsWith("Yesterday ") -> "昨天 " + english.removePrefix("Yesterday ")
        english.startsWith("Couldn't erase some items: ") -> "部分项目未能删除：" + english.removePrefix("Couldn't erase some items: ")
        else -> english
    }

